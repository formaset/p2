"""Формирование детализированных отчётов."""
from __future__ import annotations

from typing import List

from .data_models import ПланВыполнения
from .simulation import РезультатСимуляции


class ГенераторОтчётов:
    """Подготавливает текстовые отчёты для руководства и диспетчеров."""

    def __init__(self, план: ПланВыполнения, симуляция: РезультатСимуляции) -> None:
        self.план = план
        self.симуляция = симуляция

    def _строка_операции(self, номер: int, операция) -> str:
        ресурсы = [f"{р.название} ({р.тип})" for ресурсы in операция.выделенные_ресурсы.values() for р in ресурсы]
        return (
            f"{номер}. {операция.задача.название} для заказа {операция.заказ.идентификатор}"
            f" c {операция.начало:%d.%m %H:%M} по {операция.окончание:%d.%m %H:%M} \n"
            f"   Ресурсы: {', '.join(ресурсы)}\n"
        )

    def подготовить_краткий(self) -> str:
        строки: List[str] = ["=== Итоговый план ==="]
        for номер, операция in enumerate(self.план.операции, start=1):
            строки.append(self._строка_операции(номер, операция))

        строки.append("=== KPI симуляции ===")
        строки.append(f"Общая стоимость с учётом рисков: {self.симуляция.общая_стоимость:,.2f} руб.")
        строки.append(f"Средний риск: {self.симуляция.средний_риск:.2f} %")
        строки.append(f"Средний коэффициент замедления: {self.симуляция.средняя_скорость:.2f}")

        строки.append("=== Загрузка ресурсов ===")
        for название, коэффициент in self.симуляция.коэффициент_загрузки.items():
            строки.append(f"{название}: {коэффициент:.2f}")

        return "\n".join(строки)
